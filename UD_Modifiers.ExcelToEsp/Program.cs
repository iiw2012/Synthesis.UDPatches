    public class Program
    {
        static Lazy<PatchSettings> Settings = null!;

        private static ScriptEntry _GetOrAddAliasScriptFragment(Quest quest, string script_name, uint alias_num)
        {
            quest.VirtualMachineAdapter ??= new QuestAdapter();
            var script = quest.VirtualMachineAdapter.Aliases.FirstOrDefault(_ => _.Property.Alias == (short)alias_num)?.Scripts.FirstOrDefault(_ => _.Name.Equals(script_name, StringComparison.OrdinalIgnoreCase));
            if (script == default)
            {
                var fragment = new QuestFragmentAlias() { Property = new ScriptObjectProperty() { Object = (quest as ISkyrimMajorRecordGetter).ToLink(), Alias = (short)alias_num } };
                quest.VirtualMachineAdapter.Aliases.Add(fragment);
                script = new ScriptEntry() { Name = script_name, Flags = ScriptEntry.Flag.Local };
                fragment.Scripts.Add(script);
            }
            return script;
        }

        private static void AddOrEditPropertyValue<TPropType>(ILinkCache cache, ScriptEntry script, string name, string? value = null, IEnumerable<string>? list_value = null)
            where TPropType : ScriptProperty, new()
        {            
            ScriptProperty? prop = script.Properties.OfType<TPropType>().FirstOrDefault(_ => _.Name.Equals(name, StringComparison.OrdinalIgnoreCase));

            if (prop == null)
            {
                prop = new TPropType { Name = name, Flags = ScriptProperty.Flag.Edited };
                script.Properties.Add(prop);
            }
            if (typeof(TPropType) == typeof(ScriptStringProperty))
            {
                prop.Cast<ScriptStringProperty>().Data = value ?? "";
            }
            if (typeof(TPropType) == typeof(ScriptBoolProperty))
            {
                prop.Cast<ScriptBoolProperty>().Data = Convert.ToBoolean(value);
            }
            if (typeof(TPropType) == typeof(ScriptIntProperty))
            {
                prop.Cast<ScriptIntProperty>().Data = Convert.ToInt32(value);
            }
            if (typeof(TPropType) == typeof(ScriptFloatProperty))
            {
                prop.Cast<ScriptFloatProperty>().Data = Convert.ToSingle(value);
            }
            if (typeof(TPropType) == typeof(ScriptObjectProperty))
            {
                prop.Cast<ScriptObjectProperty>().Object = cache.Resolve<ISkyrimMajorRecordGetter>(value ?? "").ToLink();
            }

            if (typeof(TPropType) == typeof(ScriptStringListProperty))
            {
                prop.Cast<ScriptStringListProperty>().Data.Clear();
                prop.Cast<ScriptStringListProperty>().Data.AddRange(list_value ?? []);
            }
            if (typeof(TPropType) == typeof(ScriptBoolListProperty))
            {
                prop.Cast<ScriptBoolListProperty>().Data.Clear();
                prop.Cast<ScriptBoolListProperty>().Data.AddRange(list_value?.Select(_ => Convert.ToBoolean(_)) ?? []);
            }
            if (typeof(TPropType) == typeof(ScriptIntListProperty))
            {
                prop.Cast<ScriptIntListProperty>().Data.Clear();
                prop.Cast<ScriptIntListProperty>().Data.AddRange(list_value?.Select(_ => Convert.ToInt32(_)) ?? []);
            }
            if (typeof(TPropType) == typeof(ScriptFloatListProperty))
            {
                prop.Cast<ScriptFloatListProperty>().Data.Clear();
                prop.Cast<ScriptFloatListProperty>().Data.AddRange(list_value?.Select(_ => Convert.ToSingle(_)) ?? []);
            }
            if (typeof(TPropType) == typeof(ScriptObjectListProperty))
            {
                prop.Cast<ScriptObjectListProperty>().Objects.Clear();
                prop.Cast<ScriptObjectListProperty>().Objects.AddRange(list_value?.Select(_ =>
                {
                    if (cache.TryResolve<ISkyrimMajorRecordGetter>(_, out ISkyrimMajorRecordGetter? record))
                    {
                        return new ScriptObjectProperty { Object = record.ToLink() };
                    }
                    else
                    {
                        return new ScriptObjectProperty { };
                    }
                }) ?? []);
            }
        }

        public static async Task<int> Main(string[] args)
        {
            return await SynthesisPipeline.Instance
                .AddPatch<ISkyrimMod, ISkyrimModGetter>(RunPatch)
                .SetAutogeneratedSettings(
                    nickname: "Settings",
                    path: "settings.json",
                    out Settings)
                //.SetTypicalOpen(GameRelease.SkyrimSE, "YourPatcher.esp")
                .Run(args);
        }

        public static void RunPatch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
        {
            if (string.IsNullOrEmpty(Path.GetExtension(Settings.Value.Source.ExcelFilePath)))
            {
                Settings.Value.Source.ExcelFilePath = Path.ChangeExtension(Settings.Value.Source.ExcelFilePath, ".xlsx");
            }
            Console.WriteLine($"Loading config file with modifiers: '{Settings.Value.Source.ExcelFilePath}'");
            string? file_path;
            if (!state.TryRetrieveConfigFile(Settings.Value.Source.ExcelFilePath, out file_path))
            {
                Console.WriteLine($"\tNo file with modifiers was found. You must specify the correct file path in the patch settings.");
                return;
            }

            Console.WriteLine($"Loading mod file: '{Settings.Value.Target.ModName}'");
            ISkyrimMod target_mod;
            if (string.IsNullOrEmpty(Settings.Value.Target.ModName))
            {
                Console.WriteLine($"No mod file was specified. Results will be saved in the patch output.");
                target_mod = state.PatchMod;
            }
            else
            {
                if (string.IsNullOrEmpty(Path.GetExtension(Settings.Value.Target.ModName)))
                {
                    Settings.Value.Target.ModName = Path.ChangeExtension(Settings.Value.Target.ModName, ".esp");
                }
                target_mod = new SkyrimMod(ModKey.FromFileName(Settings.Value.Target.ModName), SkyrimRelease.SkyrimSE);
            }

            Quest? quest;
            var quest_getter = state.LoadOrder.PriorityOrder.Quest().WinningOverrides().FirstOrDefault(_ => _.EditorID == Settings.Value.Target.QuestEditorID);
            if (quest_getter != default)
            {
                quest = target_mod.Quests.GetOrAddAsOverride(quest_getter);
            }
            else
            {
                quest = target_mod.Quests.AddNew(Settings.Value.Target.QuestEditorID);
            }
            if (quest == null)
            {
                Console.WriteLine($"Unable to find or create quest with the specified EditorId '{Settings.Value.Target.QuestEditorID}'");
                return;
            }
            Console.WriteLine($"Quest FormKey: '{quest.FormKey.ID}'");

            quest.VirtualMachineAdapter ??= new QuestAdapter();
            var quest_script = quest.VirtualMachineAdapter.Scripts.FirstOrDefault(_ => _.Name.Equals("UD_ModifierStorage", StringComparison.OrdinalIgnoreCase));
            if (quest_script == null)
            {
                quest_script = new ScriptEntry() { Name = "UD_ModifierStorage" };
                quest.VirtualMachineAdapter.Scripts.Add(quest_script);
            }
            AddOrEditPropertyValue<ScriptStringProperty>(state.LinkCache, quest_script, "MODULE_ALIAS", value: "MOD_UD");
            if (Settings.Value.Target.UDInternal)
            {
                AddOrEditPropertyValue<ScriptObjectListProperty>(state.LinkCache, quest_script, "MODULE_DEP", list_value: ["UD_ModifierManager_Quest"]);
            }
            quest.NextAliasID = quest.NextAliasID ?? 0;

            using (var stream = new FileStream(file_path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite))
            using (var workbook = new XLWorkbook(stream))
            {
                if (!workbook.Worksheets.TryGetWorksheet(Settings.Value.Source.ExcelList, out IXLWorksheet? sheet))
                {
                    Console.WriteLine($"Can't open list with specified name '{Settings.Value.Source.ExcelList}'");
                    return;
                }
                var data_address = sheet.Cell(Settings.Value.Source.DataCell).Address;
                var header_address = sheet.Cell(Settings.Value.Source.HeaderCell).Address;
                int alias_name_column = -1;

                Dictionary<string, ScriptData> script_data = [];
                var cell = sheet.Cell(Settings.Value.Source.HeaderCell);

                while (cell.MergedValue().IsBlank == false)
                {
                    string script_type = cell.MergedValue().GetText() ?? "";
                    if (script_type.Equals("Alias", StringComparison.OrdinalIgnoreCase))
                    {
                        alias_name_column = cell.Address.ColumnNumber;
                    }
                    if (!script_type.ToLower().Contains("script"))
                    {
                        cell = cell.CellRight();
                        continue;
                    }
                    if (!script_data.ContainsKey(script_type))
                    {
                        script_data.Add(script_type, new ScriptData() { ScriptType = script_type });
                    }
                    string cell_value = cell.CellBelow().MergedValue().GetText();
                    if (cell_value.Equals("Script Name", StringComparison.OrdinalIgnoreCase))
                    {
                        script_data[script_type].ScriptNameColumn = cell.Address.ColumnNumber;
                        Console.WriteLine($"Script Type = {script_type}, Script Name Column = {cell.Address.ColumnNumber}");
                    }
                    else if (cell_value.Equals("Properties", StringComparison.OrdinalIgnoreCase))
                    {
                        string prop_name = cell.CellBelow().CellBelow().MergedValue().GetText();
                        string prop_type = cell.CellBelow().CellBelow().CellBelow().MergedValue().GetText();
                        int prop_index = -1;
                        var matches = Regex.Match(prop_name, "([\\w\\d_]+)(?:\\[(\\d+)\\])?");
                        if (matches.Success)
                        {
                            prop_name = matches.Groups[1].Value;
                            if (!string.IsNullOrEmpty(matches.Groups[2].Value))
                            {
                                prop_index = Convert.ToInt32(matches.Groups[2].Value);
                            }
                        }
                        if (cell_value.Length > 0)
                        {
                            script_data[script_type].Properties.Add(new ScriptPropData { Column = cell.Address.ColumnNumber, Type = prop_type, Name = prop_name, Index = prop_index });
                            Console.WriteLine($"Property Name = {prop_name}, Type = {prop_type}, Index = {prop_index}, Column = {cell.Address.ColumnNumber}");
                        }
                    }
                    cell = cell.CellRight();
                }

                int row = data_address.RowNumber;
                int col = data_address.ColumnNumber;
                QuestAlias? alias = null;

                while (!sheet.Cell(row, alias_name_column).MergedValue().IsBlank)
                {
                    string alias_name = sheet.Cell(row, alias_name_column).GetString();

                    if (!string.IsNullOrWhiteSpace(alias_name) && alias?.Name != alias_name)
                    {
                        Console.WriteLine($"\tProcessing alias '{alias_name}'");
                        alias = quest.Aliases.FirstOrDefault(_ => _.Name == alias_name);
                        if (alias == null)
                        {
                            alias = new QuestAlias() { Name = alias_name, Flags = QuestAlias.Flag.Optional, ID = quest.NextAliasID ?? 0 };
                            quest.Aliases.Add(alias);
                            quest.NextAliasID++;
                        }
                        else
                        {
                            //quest.VirtualMachineAdapter.Aliases.RemoveWhere(_ => _.Property.Alias == alias.ID);
                        }
                    }
                    if (alias == null)
                    {
                        continue;
                    }

                    foreach (var kvp in script_data)
                    {
                        var data = kvp.Value;
                        var script_name = sheet.Cell(row, data.ScriptNameColumn).GetString();

                        if (string.IsNullOrWhiteSpace(script_name)) continue;

                        Console.WriteLine($"\t\tProcessing script data for '{kvp.Key}'");

                        var alias_script = _GetOrAddAliasScriptFragment(quest, script_name, alias.ID);

                        foreach (var prop_group in data.Properties.ToLookup(_ => _.Name))
                        {
                            var prop = prop_group.First();
                            Console.WriteLine($"\t\t\tProcessing script property '{prop.Name}'");
                            try
                            {
                                if (prop_group.Count() == 1 && prop.Index == -1 && !prop.IsList && !sheet.Cell(row, prop.Column).IsEmpty())
                                {
                                    var value = sheet.Cell(row, prop.Column).GetString();
                                    switch (prop.Type.ToLower().Trim())
                                    {
                                        case "string":
                                            AddOrEditPropertyValue<ScriptStringProperty>(state.LinkCache, alias_script, prop.Name, value: value);
                                            break;
                                        case "bool":
                                            AddOrEditPropertyValue<ScriptBoolProperty>(state.LinkCache, alias_script, prop.Name, value: value);
                                            break;
                                        case "float":
                                            AddOrEditPropertyValue<ScriptFloatProperty>(state.LinkCache, alias_script, prop.Name, value: value);
                                            break;
                                        case "integer":
                                        case "int":
                                            AddOrEditPropertyValue<ScriptIntProperty>(state.LinkCache, alias_script, prop.Name, value: value);
                                            break;
                                        case "form":
                                            AddOrEditPropertyValue<ScriptObjectProperty>(state.LinkCache, alias_script, prop.Name, value: value);
                                            break;
                                        default:
                                            break;
                                    }
                                }
                                else if (prop_group.Count() == 1 && prop.Index == -1 && prop.IsList && !sheet.Cell(row, prop.Column).IsEmpty())
                                {
                                    var list_values = sheet.Cell(row, prop.Column).GetString().Split([",", "\n", "\r", "\r\n"], StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries);
                                    switch (prop.Type.ToLower().Trim())
                                    {
                                        case "string list":
                                            AddOrEditPropertyValue<ScriptStringListProperty>(state.LinkCache, alias_script, prop.Name, list_value: list_values);
                                            break;
                                        case "bool list":
                                            AddOrEditPropertyValue<ScriptBoolListProperty>(state.LinkCache, alias_script, prop.Name, list_value: list_values);
                                            break;
                                        case "float list":
                                            AddOrEditPropertyValue<ScriptFloatListProperty>(state.LinkCache, alias_script, prop.Name, list_value: list_values);
                                            break;
                                        case "integer list":
                                        case "int list":
                                            AddOrEditPropertyValue<ScriptIntListProperty>(state.LinkCache, alias_script, prop.Name, list_value: list_values);
                                            break;
                                        case "form list":
                                            AddOrEditPropertyValue<ScriptObjectListProperty>(state.LinkCache, alias_script, prop.Name, list_value: list_values);
                                            break;
                                        default:
                                            break;
                                    }
                                }
                                else if (prop_group.Any() && prop.Index > -1)
                                {
                                    var list_values = prop_group.OrderBy(_ => _.Index).Select(p => sheet.Cell(row, p.Column).GetString().Trim());
                                    if (Settings.Value.Target.TrimArrays)
                                    {
                                        list_values = list_values.Reverse().SkipWhile(_ => String.IsNullOrEmpty(_)).Reverse();
                                    }
                                    switch (prop.Type.ToLower().Trim())
                                    {
                                        case "string":
                                            AddOrEditPropertyValue<ScriptStringListProperty>(state.LinkCache, alias_script, prop.Name, list_value: list_values);
                                            break;
                                        case "bool":
                                            AddOrEditPropertyValue<ScriptBoolListProperty>(state.LinkCache, alias_script, prop.Name, list_value: list_values);
                                            break;
                                        case "float":
                                            AddOrEditPropertyValue<ScriptFloatListProperty>(state.LinkCache, alias_script, prop.Name, list_value: list_values);
                                            break;
                                        case "integer":
                                        case "int":
                                            AddOrEditPropertyValue<ScriptIntListProperty>(state.LinkCache, alias_script, prop.Name, list_value: list_values);
                                            break;
                                        case "form":
                                            AddOrEditPropertyValue<ScriptObjectListProperty>(state.LinkCache, alias_script, prop.Name, list_value: list_values);
                                            break;
                                        default:
                                            break;
                                    }
                                }
                            }
                            catch (Exception ex) 
                            {
                                Console.WriteLine($"\t\t\t\t{ex.Message}");
                            }
                        }
                    }
                    row++;
                }
            }
            if (!string.IsNullOrEmpty(Settings.Value.Target.ModName) && target_mod != state.PatchMod)
            {
                Console.WriteLine($"Saving results into mod file '{Settings.Value.Target.ModName}'");
                target_mod.WriteToBinary(Path.Combine(state.DataFolderPath, Settings.Value.Target.ModName));
            }
        }
    }
}
