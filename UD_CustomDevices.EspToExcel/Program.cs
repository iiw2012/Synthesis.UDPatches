using ClosedXML.Excel;
using Mutagen.Bethesda;
using Mutagen.Bethesda.Skyrim;
using Mutagen.Bethesda.Synthesis;
using Noggog;
using System.Text.RegularExpressions;
using UD_Common;

namespace UD_CustomDevices.EspToExcel
{
    public class Program
    {
        static Lazy<PatchSettings> Settings = null!;

        public static async Task<int> Main(string[] args)
        {
            return await SynthesisPipeline.Instance
                .AddPatch<ISkyrimMod, ISkyrimModGetter>(RunPatch)
                .SetAutogeneratedSettings(
                    nickname: "Settings",
                    path: "settings.json",
                    out Settings)
                //.SetTypicalOpen(GameRelease.SkyrimSE, "YourPatcher.esp")
                .Run(args);
        }

        public static void RunPatch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
        {
            try
            {
                string? file_path;
                state.TryRetrieveConfigFile(Settings.Value.Target.ExcelFilePath, out file_path);
                Console.WriteLine($"Loading config file with modifiers '{file_path}'");

                if (file_path == null)
                {
                    Console.WriteLine("\tUnable to load Excel file!");
                    return;
                }

                //using (var stream = new FileStream(config_path, FileMode.Open, FileAccess.ReadWrite, FileShare.None))
                using (var workbook = new XLWorkbook(file_path))
                {
                    if (!workbook.Worksheets.TryGetWorksheet(Settings.Value.Target.ExcelList, out IXLWorksheet? sheet))
                    {
                        sheet = workbook.Worksheets.Add(Settings.Value.Target.ExcelList);
                    }
                    var data_address = sheet.Cell(Settings.Value.Target.DataCell).Address;
                    var header_address = sheet.Cell(Settings.Value.Target.HeaderCell).Address;

                    Dictionary<string, ScriptData> script_data = [];
                    var cell = sheet.Cell(Settings.Value.Target.HeaderCell);

                    while (cell.MergedValue().IsBlank == false)
                    {
                        string script_type = cell.MergedValue().GetText() ?? "";
                        if (!script_type.ToLower().Contains("script"))
                        {
                            cell = cell.CellRight();
                            continue;
                        }
                        if (!script_data.ContainsKey(script_type))
                        {
                            script_data.Add(script_type, new ScriptData() { ScriptType = script_type });
                        }
                        string cell_value = cell.CellBelow().MergedValue().GetText();
                        if (cell_value.Equals("Script Name", StringComparison.OrdinalIgnoreCase))
                        {
                            script_data[script_type].ScriptNameColumn = cell.Address.ColumnNumber;
                            Console.WriteLine($"Script Type = {script_type}, Script Name Column = {cell.Address.ColumnNumber}");
                        }
                        else if (cell_value.Equals("Properties", StringComparison.OrdinalIgnoreCase))
                        {
                            string prop_name = cell.CellBelow().CellBelow().MergedValue().GetText();
                            string prop_type = cell.CellBelow().CellBelow().CellBelow().MergedValue().GetText();
                            int prop_index = -1;
                            var matches = Regex.Match(prop_name, "([\\w\\d_]+)(?:\\[(\\d+)\\])?");
                            if (matches.Success)
                            {
                                prop_name = matches.Groups[1].Value;
                                if (!string.IsNullOrEmpty(matches.Groups[2].Value))
                                {
                                    prop_index = Convert.ToInt32(matches.Groups[2].Value);
                                }
                            }
                            if (cell_value.Length > 0)
                            {
                                script_data[script_type].Properties.Add(new ScriptPropData { Column = cell.Address.ColumnNumber, Type = prop_type, Name = prop_name, Index = prop_index });
                                Console.WriteLine($"Property Name = {prop_name}, Type = {prop_type}, Index = {prop_index}, Column = {cell.Address.ColumnNumber}");
                            }
                        }
                        cell = cell.CellRight();
                    }

                    var armors = state.LoadOrder.PriorityOrder.Armor().WinningOverrides().Where(_ => _.VirtualMachineAdapter != null);
                    if (!String.IsNullOrEmpty(Settings.Value.DeviceFilter.ByKeyword))
                    {
                        armors = armors.Where(_ => _.Keywords?.Any(kw => kw.Resolve(state.LinkCache).EditorID?.Equals(Settings.Value.DeviceFilter.ByKeyword, StringComparison.OrdinalIgnoreCase) == true) == true);
                    }
                    if (!String.IsNullOrEmpty(Settings.Value.DeviceFilter.ByEditorID))
                    {
                        var pattern = Settings.Value.DeviceFilter.ByEditorID.Replace("*", ".*").Replace("?", ".?");
                        armors = armors.Where(_ => new Regex(pattern, RegexOptions.IgnoreCase).IsMatch(_.EditorID ?? ""));
                    }

                    int row = data_address.RowNumber;
                    int col = data_address.ColumnNumber;
                    foreach (var ar in armors)
                    {
                        col = data_address.ColumnNumber;
                        sheet.Cell(row, col++).Value = ar.EditorID;
                        sheet.Cell(row, col++).Value = ar.Name?.String ?? "";

                        foreach (var armor_script in ar.VirtualMachineAdapter?.Scripts ?? [])
                        {
                            try
                            {
                                ScriptData? data = null;
                                Console.WriteLine($"\t\tProcessing script '{armor_script.Name}'");
                                // Modifier script
                                data = script_data.FirstOrDefault().Value;
                                // print into the first alias row
                                sheet.Cell(row, data.ScriptNameColumn).Value = armor_script.Name;
                                data.PrintScriptProperties(sheet, row, armor_script, state.LinkCache);
                                row++;
                            }
                            catch (Exception e)
                            {
                                Console.WriteLine($"\t\t\tException while processing alias script: {e.Message}");
                            }
                        }
                    }
                    var right_col = script_data.SelectMany(_ => _.Value.Properties.Select(_ => _.Column)).Max();
                    sheet.Range(data_address.RowNumber, data_address.ColumnNumber, row - 1, right_col).Style.Alignment.SetVertical(XLAlignmentVerticalValues.Center);
                    sheet.Range(data_address.RowNumber, data_address.ColumnNumber, row - 1, right_col).Style.Border.SetInsideBorder(XLBorderStyleValues.Thin);
                    sheet.Range(data_address.RowNumber, data_address.ColumnNumber, row - 1, right_col).Style.Border.SetOutsideBorder(XLBorderStyleValues.Thin);
                    workbook.Save();
                }
            }
            catch (Exception ex)
            {
                Console.WriteLine(ex.Message);
            }
        }
    }
}
